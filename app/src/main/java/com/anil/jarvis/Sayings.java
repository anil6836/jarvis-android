    static String riddle(Context c) {
        int i = next(c, "riddles", RIDDLES.length);
        sp(c).edit().putInt("asked", i).putLong("asked_at", System.currentTimeMillis()).apply();
        return "పొడుపు కథ: " + RIDDLES[i][0] + " (తెలియకపోతే \"చెప్పు\" అనండి.)";
    }

    /** A riddle asked in the last 10 minutes and still open: its index, else -1. */
    static int open(Context c) {
        SharedPreferences s = sp(c);
        int i = s.getInt("asked", -1);
        if (i < 0 || i >= RIDDLES.length || System.currentTimeMillis() - s.getLong("asked_at", 0) > 10 * 60_000L) return -1;
        return i;
    }

    /** His guess / "చెప్పు" / "క్లూ" to the open riddle: what to say, or null when his words aren't about it. */
    static String answer(Context c, String said) {
        int i = open(c);
        if (i < 0) return null;
        String r = check(i, said);
        if (r == null) return null;
        if (!r.startsWith("క్లూ") && !r.startsWith("కాదు")) sp(c).edit().putInt("asked", -1).apply(); // (over)
        return r;
    }

    /** Plain part (tested on the desk). */
    static String check(int i, String said) {
        String t = said == null ? "" : said.toLowerCase(Locale.ROOT).replace("‌", "").trim();
        String[] q = RIDDLES[i];
        for (String w : q[2].split("\\|")) if (!w.isEmpty() && t.contains(w.toLowerCase(Locale.ROOT))) return "సరిగ్గా చెప్పారు! జవాబు " + q[1] + ".";
        if (t.matches(".*(క్లూ|clue|హింట్|hint|సూచన).*")) {
            return "క్లూ: జవాబు \"" + q[1].charAt(0) + "\" తో మొదలవుతుంది.";
        }
        if (t.matches(".*(చెప్పు|చెప్పండి|తెలియదు|తెలీదు|నాకు తెలియదు|ఓడిపోయాను|వదిలేస్తా|జవాబు ఏంటి|జవాబు|answer|i give up).*"))
            return "జవాబు: " + q[1] + ".";
        if (t.split("\\s+").length <= 3 && !t.isEmpty() && !COMMAND.matcher(t).find())
            return "కాదు. మళ్లీ ఆలోచించండి, లేదా \"క్లూ\" / \"చెప్పు\" అనండి.";
        return null;
    }

    /** Words of a command, never a guess ("లైట్ ఆన్ చెయ్", "అమ్మకి కాల్", "టైమర్ పెట్టు", "ఆపద"). */
    private static final java.util.regex.Pattern COMMAND = java.util.regex.Pattern.compile(
            "(ఆపు|వద్దు|స్టాప్|stop|సరే|ok|ఓకే|ఆన్|ఆఫ్|\\bon\\b|\\boff\\b|కాల్|ఫోన్|పంపు|పెట్టు|చెయ్|చేయి|చేయండి|తెరువు|గుర్తు|టైమర్|అలారం|లైట్|టార్చ్|పాట|"
                    + "ఆపద|కాపాడు|సహాయం|హెల్ప్|help|sos|అంబులెన్స్|పోలీస్|108|112|100|101|ఎక్కడ|ఎంత|టైమ్|బ్యాటరీ|వెతుకు|నోట్|డైరీ|లిస్ట్)", java.util.regex.Pattern.CASE_INSENSITIVE);

    /** He asks for one ("ఒక సామెత చెప్పు", "పొడుపు కథ అడుగు"). */
    static boolean asksProverb(String t) { return t.matches("(?s).*(సామెత|సామెతలు|proverb).*") && !t.contains("అర్థం ఏంటి"); }

    static boolean asksRiddle(String t) { return t.matches("(?s).*(పొడుపు\\s*కథ|పొడుపుకథ|పొడుపు కధ|riddle).*"); }
