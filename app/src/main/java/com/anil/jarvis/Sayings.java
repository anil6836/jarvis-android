    private static SharedPreferences sp(Context c) { return c.getSharedPreferences("jarvis_sayings", Context.MODE_PRIVATE); }
    private static final Random rnd = new Random();

    /** The next one of a list not told yet (all told: they start again). */
    private static int next(Context c, String key, int size) {
        SharedPreferences s = sp(c);
        String told = s.getString(key, ",");
        java.util.List<Integer> left = new java.util.ArrayList<>();
        for (int i = 0; i < size; i++) if (!told.contains("," + i + ",")) left.add(i);
        if (left.isEmpty()) { told = ","; for (int i = 0; i < size; i++) left.add(i); }
        int pick = left.get(rnd.nextInt(left.size()));
        s.edit().putString(key, told + pick + ",").apply();
        return pick;
    }

    /** "ఒక సామెత చెప్పు". */
    static String proverb(Context c) {
        String[] p = PROVERBS[next(c, "proverbs", PROVERBS.length)];
        return "సామెత: \"" + p[0] + "\" అర్థం: " + p[1];
    }

